CREATE TABLE IF NOT EXISTS analytics_race_summary (
    run_id                  BIGINT NOT NULL REFERENCES analytics_runs ON DELETE CASCADE,
    session_key             BIGINT NOT NULL,
    circuit_short_name      TEXT,
    n_drivers               INT,
    n_laps                  INT,
    fastest_team            TEXT,
    fastest_team_avg        DOUBLE PRECISION,
    slowest_team            TEXT,
    slowest_team_avg        DOUBLE PRECISION,
    team_spread_s           DOUBLE PRECISION,
    fastest_driver          TEXT,
    fastest_driver_avg      DOUBLE PRECISION,
    slowest_driver          TEXT,
    slowest_driver_avg      DOUBLE PRECISION,
    driver_spread_s         DOUBLE PRECISION,
    avg_soft_stint          DOUBLE PRECISION,
    avg_medium_stint        DOUBLE PRECISION,
    avg_hard_stint          DOUBLE PRECISION,
    soft_deg_s_per_lap      DOUBLE PRECISION,
    medium_deg_s_per_lap    DOUBLE PRECISION,
    hard_deg_s_per_lap      DOUBLE PRECISION,
    PRIMARY KEY (run_id, session_key)
);
